import type * as C from "@mono-agent/contracts";
import type * as W from "./contracts.js";

/** JSON body DTO registry. Names are stable references in the v1 route manifest.
 * Wrappers here describe server.ts responses; domain data stays in contracts.ts.
 * NoBody, Binary and Html are transport descriptors, not JSON DTOs.
 */
export interface WebApiDtos {
  readonly ApiEmpty: Record<string, never>;
  readonly ApiHealth: { readonly status: "ok"; readonly version: 1; readonly push: "ok" | "degraded" };
  readonly ApiBootstrap: W.WebBootstrap;
  readonly ApiBootstrapQuery: W.WebBootstrapScope;
  readonly ApiAgent: { readonly agent: W.WebAgentSummary };
  readonly ApiPatchAgent: W.PatchWebAgentInput;
  readonly ApiPutRunDefaults: W.PutWebAgentRunSettingsInput;
  readonly ApiProviderUsage: C.ProviderUsageSnapshot;
  readonly ApiProviderQuery: { readonly provider?: C.ProviderUsageId };
  readonly ApiRestart: W.WebAgentRestartOperation;
  readonly ApiLatestRestart: { readonly operation: W.WebAgentRestartOperation | null };
  readonly ApiProviderAuth: C.ProviderAuthStatusSnapshot;
  readonly ApiAuthStart: C.ProviderAuthSessionStartInput;
  readonly ApiAuthSession: C.ProviderAuthSessionSnapshot;
  readonly ApiAuthInput: C.ProviderAuthSessionInput;
  readonly ApiAuthCheckStart: C.ProviderAuthCheckStartInput;
  readonly ApiAuthCheck: C.ProviderAuthCheckSessionSnapshot;
  readonly ApiSkills: W.WebSkillRegistry;
  readonly ApiCronOverview: W.WebCronOverview;
  readonly ApiCronConfig: { readonly configView: W.WebChannelConfigView };
  readonly ApiCronRunsQuery: { readonly limit?: number; readonly before?: string };
  readonly ApiCronRuns: W.WebCronRunPage;
  readonly ApiModelsQuery: { readonly limit?: number; readonly provider?: string; readonly q?: string; readonly cursor?: string };
  readonly ApiModels: W.WebModelPage;
  readonly ApiCronRun: { readonly message: W.WebMessage };
  readonly ApiCronReply: W.CreateWebCronReplyInput;
  readonly ApiCronReceipt: W.WebCronReplyReceipt;
  readonly ApiCronAction: { readonly idempotencyKey: string; readonly confirmationToken?: string };
  readonly ApiCronEnable: { readonly idempotencyKey: string; readonly confirmationToken?: string; readonly enabled: boolean };
  readonly ApiCronRunResult: W.WebCronMutationResult<{ readonly run: W.WebCronRunSummary }>;
  readonly ApiCronEnableResult: W.WebCronMutationResult<{ readonly job: W.WebCronJob }>;
  readonly ApiCreateThread: W.CreateWebThreadInput;
  readonly ApiThread: { readonly thread: W.WebThread };
  readonly ApiSourceQuery: { readonly sourceId: string };
  readonly ApiTags: { readonly tags: readonly W.WebTag[] };
  readonly ApiCreateTag: W.CreateWebTagInput;
  readonly ApiPatchTag: W.PatchWebTagInput;
  readonly ApiTag: { readonly tag: W.WebTag };
  readonly ApiProjects: { readonly projects: readonly W.WebProject[] };
  readonly ApiCreateProject: W.CreateWebProjectInput;
  readonly ApiPatchProject: W.PatchWebProjectInput;
  readonly ApiProject: { readonly project: W.WebProject };
  readonly ApiThreadsQuery: { readonly sourceId: string; readonly archived: boolean; readonly scope?: W.WebThreadListScope; readonly limit?: number; readonly before?: string; readonly tagId?: string; readonly projectId?: string };
  readonly ApiThreadPage: W.WebThreadPage;
  readonly ApiSearchQuery: { readonly sourceId: string; readonly q?: string; readonly limit?: number; readonly scope?: W.WebThreadListScope };
  readonly ApiSearch: W.WebThreadSearchPage;
  readonly ApiActiveThreads: W.WebActiveThreads;
  readonly ApiToolCall: { readonly part: Extract<W.WebMessagePart, { readonly type: "tool-call" | "subagent" }> };
  readonly ApiFullQuery: { readonly full?: "1" | "true" };
  readonly ApiMessage: { readonly message: W.WebMessage };
  readonly ApiThreadUsage: { readonly usage: W.WebThreadUsage };
  readonly ApiThreadDetail: W.WebThreadDetail;
  readonly ApiMessagesQuery: { readonly before?: string; readonly limit?: number; readonly full?: "1" | "true" };
  readonly ApiMessagePage: W.WebMessagePage;
  readonly ApiAttachmentAccess: { readonly part: Extract<W.WebMessagePart, { readonly type: "attachment" }> };
  readonly ApiCapabilityQuery: { readonly expires: string; readonly token: string };
  readonly ApiMcpAppAccess: { readonly part: Extract<W.WebMessagePart, { readonly type: "mcp_app" }> };
  readonly ApiMcpAppResource: C.AgentMcpAppResource;
  readonly ApiMcpAppRequest: { readonly method: "resources/read" | "tools/call" | "ui/open-link" | "ui/update-model-context"; readonly params?: unknown; readonly confirmed?: boolean };
  readonly ApiMcpAppResult: { readonly result: unknown };
  readonly ApiJob: { readonly job: C.ProcessJobProjection };
  readonly ApiWakeSchedule: { readonly schedule: W.WebWakeSchedule | null };
  readonly ApiCreateWake: W.WebWakeScheduleDefinition;
  readonly ApiPutWake: W.WebWakeScheduleDefinition & { readonly expectedRevision: number };
  readonly ApiPatchWake: { readonly expectedRevision: number; readonly state: "active" | "paused" };
  readonly ApiDeleteWake: { readonly expectedRevision: number };
  readonly ApiPatchThread: W.PatchWebThreadInput;
  readonly ApiDeleteThreadQuery: { readonly emptyOnly?: true };
  readonly ApiCompaction: C.AgentManualCompactionResult;
  readonly ApiStartTurn: W.StartWebTurnInput;
  readonly ApiStartedTurn: { readonly thread: W.WebThread; readonly turn: W.WebRunState };
  readonly ApiStartSubmission: W.StartWebSubmissionInput;
  readonly ApiSubmissionReceipt: W.WebSubmissionReceipt;
  readonly ApiLiveInput: W.StartWebLiveInputInput;
  readonly ApiLiveInputReceipt: W.WebLiveInputReceipt;
  readonly ApiCancel: { readonly origin?: W.WebCancelOrigin };
  readonly ApiCancelled: { readonly cancelled: true; readonly thread: W.WebThread };
  readonly ApiAsk: { readonly ask: C.ChannelAskSnapshot | null };
  readonly ApiAnswerAsk: { readonly interactionId: string; readonly answers: readonly C.ChannelAskAnswer[] };
  readonly ApiAskResult: C.ChannelAskSubmissionResult;
  readonly ApiPushSubscriptionInput: { readonly endpoint: string; readonly previousSubscriptionId?: string; readonly previousEndpoint?: string; readonly expirationTime?: number | null; readonly keys: { readonly p256dh: string; readonly auth: string } };
  readonly ApiPushSubscription: { readonly subscription: W.WebPushSubscriptionStatus };
  readonly ApiPushAck: { readonly subscriptionId: string; readonly ackToken: string };
  readonly ApiCreateUpload: W.CreateWebUploadInput;
  readonly ApiUpload: { readonly attachment: W.WebAttachment };
  readonly ApiEventsQuery: { readonly thread?: string };
  readonly ApiEvent: W.WebTypedEvent;
  readonly ApiEventPayloadMap: W.WebEventPayloadMap;
  readonly ApiDeltaVectors: readonly { readonly name: string; readonly prev: readonly W.WebMessagePart[]; readonly next: readonly W.WebMessagePart[]; readonly ops: readonly W.WebMessageDeltaOp[] }[];
  readonly ApiError: { readonly error: { readonly code: string; readonly message: string } | string };
}
